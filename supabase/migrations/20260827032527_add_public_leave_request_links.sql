CREATE OR REPLACE FUNCTION public.resolve_leave_public_context(p_token text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_token public.leave_public_access_tokens%ROWTYPE;
  v_company public.companies%ROWTYPE;
BEGIN
  SELECT * INTO v_token
  FROM public.leave_public_access_tokens token
  WHERE token.token_hash = extensions.digest(coalesce(p_token, ''), 'sha256')
    AND token.is_active
    AND (token.expires_at IS NULL OR token.expires_at > now());
  IF NOT FOUND THEN RETURN jsonb_build_object('valid', false); END IF;
  SELECT * INTO v_company FROM public.companies company WHERE company.id = v_token.company_id;
  RETURN jsonb_build_object(
    'valid', true,
    'token_id', v_token.id,
    'company_id', v_token.company_id,
    'company', jsonb_build_object('name', v_company.name, 'horizontal_logo_url', v_company.horizontal_logo_url)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.identify_leave_public_employee(
  p_token text,
  p_document_type text,
  p_document_number text,
  p_birth_date date,
  p_ip_hash text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_token public.leave_public_access_tokens%ROWTYPE;
  v_employee public.employees_v2%ROWTYPE;
  v_document text := public.normalize_document_number(p_document_number);
  v_identity_hash bytea;
  v_ip_hash bytea;
  v_failed integer;
  v_identity_found boolean;
  v_session text;
  v_types jsonb;
BEGIN
  SELECT * INTO v_token
  FROM public.leave_public_access_tokens token
  WHERE token.token_hash = extensions.digest(coalesce(p_token, ''), 'sha256')
    AND token.is_active
    AND (token.expires_at IS NULL OR token.expires_at > now());
  IF NOT FOUND THEN RETURN jsonb_build_object('success', false, 'code', 'invalid_link'); END IF;

  v_ip_hash := CASE WHEN coalesce(p_ip_hash, '') ~ '^[0-9a-fA-F]{64}$'
    THEN decode(p_ip_hash, 'hex') ELSE extensions.digest('unknown', 'sha256') END;
  v_identity_hash := extensions.digest(
    upper(coalesce(btrim(p_document_type), '')) || ':' || coalesce(v_document, '') || ':' || coalesce(p_birth_date::text, ''),
    'sha256'
  );

  -- Serialize attempts sharing either the IP or normalized identity. Without
  -- both locks, concurrent requests could all observe fewer than five failures
  -- before inserting their own attempt and bypass the fifteen-minute limit.
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_token.id::text || ':ip:' || encode(v_ip_hash, 'hex'), 0)
  );
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_token.id::text || ':identity:' || encode(v_identity_hash, 'hex'), 0)
  );

  DELETE FROM public.leave_public_identity_sessions
  WHERE expires_at < now() - interval '7 days';
  DELETE FROM public.leave_public_access_attempts
  WHERE attempted_at < now() - interval '7 days';

  SELECT count(*)::integer INTO v_failed
  FROM public.leave_public_access_attempts attempt
  WHERE attempt.access_token_id = v_token.id
    AND NOT attempt.success
    AND attempt.attempted_at > now() - interval '15 minutes'
    AND (attempt.ip_hash = v_ip_hash OR attempt.identity_hash = v_identity_hash);
  IF v_failed >= 5 THEN RETURN jsonb_build_object('success', false, 'code', 'rate_limited'); END IF;

  SELECT * INTO v_employee
  FROM public.employees_v2 employee
  WHERE employee.company_id = v_token.company_id
    AND employee.document_type::text = upper(btrim(coalesce(p_document_type, '')))
    AND public.normalize_document_number(employee.document_number) = v_document
    AND employee.birth_date = p_birth_date
    AND employee.is_active
    AND employee.status = 'active'
    AND EXISTS (
      SELECT 1 FROM public.employee_employment_cycles cycle
      WHERE cycle.employee_id = employee.id
        AND cycle.company_id = employee.company_id
        AND cycle.status = 'active'
    )
  LIMIT 1;

  v_identity_found := FOUND;

  INSERT INTO public.leave_public_access_attempts (access_token_id, identity_hash, ip_hash, success)
  VALUES (v_token.id, v_identity_hash, v_ip_hash, v_identity_found);

  IF NOT v_identity_found THEN
    RETURN jsonb_build_object('success', false, 'code', 'invalid_identity');
  END IF;

  v_session := encode(extensions.gen_random_bytes(32), 'hex');
  INSERT INTO public.leave_public_identity_sessions (
    access_token_id, company_id, employee_id, session_hash, expires_at, ip_hash
  ) VALUES (
    v_token.id, v_token.company_id, v_employee.id,
    extensions.digest(v_session, 'sha256'), now() + interval '10 minutes', v_ip_hash
  );

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'leave_type', config.leave_type,
    'display_name', config.display_name,
    'description', config.description,
    'requires_document', config.requires_document,
    'document_description', config.document_description,
    'min_days_advance', config.min_days_advance,
    'allows_half_day', config.allows_half_day,
    'allows_hours', config.allows_hours,
    'max_days_per_year', config.max_days_per_year
  ) ORDER BY config.display_name), '[]'::jsonb) INTO v_types
  FROM public.leave_type_config config
  WHERE config.company_id = v_token.company_id AND config.is_active;

  RETURN jsonb_build_object(
    'success', true,
    'session', v_session,
    'expires_in_seconds', 600,
    'employee_first_name', v_employee.first_name,
    'leave_types', v_types
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.prepare_leave_public_submission(p_session text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_session public.leave_public_identity_sessions%ROWTYPE;
  v_reference text;
BEGIN
  SELECT * INTO v_session
  FROM public.leave_public_identity_sessions session
  WHERE session.session_hash = extensions.digest(coalesce(p_session, ''), 'sha256');
  IF NOT FOUND THEN RETURN jsonb_build_object('valid', false); END IF;
  IF v_session.used_at IS NOT NULL AND v_session.created_request_id IS NOT NULL THEN
    SELECT request.public_reference INTO v_reference
    FROM public.leave_requests request WHERE request.id = v_session.created_request_id;
    RETURN jsonb_build_object('valid', true, 'completed', true, 'reference', v_reference);
  END IF;
  IF v_session.expires_at <= now() OR NOT EXISTS (
    SELECT 1 FROM public.leave_public_access_tokens token
    WHERE token.id = v_session.access_token_id AND token.is_active
      AND (token.expires_at IS NULL OR token.expires_at > now())
  ) THEN RETURN jsonb_build_object('valid', false); END IF;
  RETURN jsonb_build_object(
    'valid', true, 'completed', false,
    'company_id', v_session.company_id, 'employee_id', v_session.employee_id
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_leave_public_request(
  p_session text,
  p_request jsonb,
  p_document_url text DEFAULT NULL,
  p_document_name text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_session public.leave_public_identity_sessions%ROWTYPE;
  v_request public.leave_requests%ROWTYPE;
  v_reference text;
BEGIN
  SELECT * INTO v_session
  FROM public.leave_public_identity_sessions session
  WHERE session.session_hash = extensions.digest(coalesce(p_session, ''), 'sha256')
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'La sesión de verificación no es válida.' USING ERRCODE = '42501'; END IF;
  IF v_session.used_at IS NOT NULL AND v_session.created_request_id IS NOT NULL THEN
    SELECT request.public_reference INTO v_reference
    FROM public.leave_requests request WHERE request.id = v_session.created_request_id;
    RETURN jsonb_build_object('success', true, 'reference', v_reference, 'idempotent', true);
  END IF;
  IF v_session.expires_at <= now() OR NOT EXISTS (
    SELECT 1 FROM public.leave_public_access_tokens token
    WHERE token.id = v_session.access_token_id AND token.is_active
      AND (token.expires_at IS NULL OR token.expires_at > now())
  ) THEN RAISE EXCEPTION 'La sesión de verificación expiró.' USING ERRCODE = '42501'; END IF;

  v_request := private.create_leave_request_core(
    v_session.company_id, v_session.employee_id, p_request, NULL, 'public_link',
    v_session.access_token_id, p_document_url, p_document_name
  );
  UPDATE public.leave_public_identity_sessions
  SET used_at = now(), created_request_id = v_request.id
  WHERE id = v_session.id;
  RETURN jsonb_build_object('success', true, 'reference', v_request.public_reference, 'idempotent', false);
END;
$$;

