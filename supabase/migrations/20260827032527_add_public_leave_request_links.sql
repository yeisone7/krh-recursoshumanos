  AND NOT (
    coalesce((storage.foldername(name))[2], '') = 'leaves'
    AND coalesce((storage.foldername(name))[3], '') = 'public'
  )
  AND (
    EXISTS (
      SELECT 1 FROM public.user_company_assignments assignment
      WHERE assignment.user_id = (SELECT auth.uid())
        AND assignment.company_id::text = (storage.foldername(name))[1]
    )
    OR public.is_admin()
  )
);

