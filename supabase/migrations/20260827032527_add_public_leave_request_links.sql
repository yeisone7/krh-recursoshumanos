CREATE OR REPLACE FUNCTION public.create_leave_request_workflow(p_request jsonb)
RETURNS public.leave_requests
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id uuid := (SELECT auth.uid());
  v_employee_id uuid := nullif(p_request->>'employee_id', '')::uuid;
  v_company_id uuid;
  v_source text;
BEGIN
  IF v_user_id IS NULL OR v_employee_id IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para crear la solicitud.' USING ERRCODE = '42501';
  END IF;
  SELECT employee.company_id INTO v_company_id
  FROM public.employees_v2 employee WHERE employee.id = v_employee_id;
  IF v_company_id IS NULL THEN
    RAISE EXCEPTION 'Empleado no encontrado.' USING ERRCODE = '22023';
  END IF;
  IF NOT (
    v_employee_id = public.get_my_employee_id()
    OR (
      public.can_access_absence_employee(v_employee_id)
      AND (
        public.is_super_admin() OR public.is_admin_or_rrhh()
        OR public.check_user_permission(v_user_id, 'permisos', 'create')
      )
    )
  ) THEN
    RAISE EXCEPTION 'No tienes permiso para crear esta solicitud.' USING ERRCODE = '42501';
  END IF;
  v_source := CASE WHEN v_employee_id = public.get_my_employee_id() THEN 'employee_portal' ELSE 'internal' END;
  RETURN private.create_leave_request_core(
    v_company_id, v_employee_id, p_request, v_user_id, v_source, NULL,
    p_request->>'document_url', p_request->>'document_name'
  );
END;
$$;

